  function hash(str) {
    let h = 5381;
    for (let i = 0; i < str.length; i++) h = ((h << 5) + h + str.charCodeAt(i)) >>> 0;
    return h;
  }

  /**
   * เลือกแบบข้อความ: หมุนตาม hash ของ user_id + log_date โดยต่อวันขยับทีละ step (1..n-1)
   * จึงรับประกันว่าสองวันติดกันไม่ได้แบบเดิม และคนละคนได้ลำดับต่างกัน
   */
  function pick(key, list, ctx) {
    const n = list.length;
    if (n === 1) return list[0];
    const userId = (ctx && ctx.userId) || '';
    const logDate = (ctx && ctx.logDate) || '1970-01-01';
    const [y, m, d] = logDate.split('-').map(Number);
    const dayNo = Math.floor(Date.UTC(y, m - 1, d) / 86400000);
    const base = hash(`${userId}|${key}`) % n;
    const step = 1 + (hash(`${userId}|${key}|step`) % (n - 1));
    return list[(base + dayNo * step) % n];
  }

